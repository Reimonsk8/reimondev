#!/usr/bin/env node
// Export pixelfx effects as game-ready horizontal sprite strips.
//
//   npm run vfx                      # every effect in scripts/vfx/effects.mjs
//   npm run vfx -- slash heal        # only the named slugs
//   npm run vfx -- --list            # what is configured
//
// Output: frontend/public/sprites/vfx/<slug>/
//   strip.png    one row, frames left to right, transparent
//   manifest.json  frame size, count, fps, pivot, duration, loop
// plus frontend/public/sprites/vfx/index.json describing everything exported.
//
// The strip format is deliberately dumb: SOS animates it with CSS
// `steps(n)` + `background-position`, Outlands slices it into PIXI textures.
// No game code needs to know anything about pixelfx.

import { mkdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadEffect, renderFrames } from '../../vendor/pixelfx/tools/lib/fxlib.mjs';
import { encodePNG } from '../../vendor/pixelfx/tools/lib/png.mjs';
import { EFFECTS } from './effects.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const GAME_ROOT = join(HERE, '..', '..');
const OUT_ROOT = join(GAME_ROOT, 'frontend', 'public', 'sprites', 'vfx');

// Keep strips under the smallest WebGL/CSS texture limit we care about.
const MAX_STRIP_WIDTH = 8192;

const args = process.argv.slice(2);
const flags = new Set(args.filter((a) => a.startsWith('--')));
const wanted = args.filter((a) => !a.startsWith('--'));

if (flags.has('--list')) {
  for (const e of EFFECTS) console.log(`${e.slug.padEnd(18)} ${e.effect}  ${e.fps}fps${e.loop ? ' loop' : ''}`);
  process.exit(0);
}

const chosen = wanted.length ? EFFECTS.filter((e) => wanted.includes(e.slug)) : EFFECTS;
if (!chosen.length) {
  console.error(`no configured effect matches ${wanted.join(', ')}`);
  process.exit(1);
}

const index = existsSync(join(OUT_ROOT, 'index.json'))
  ? JSON.parse(readFileSync(join(OUT_ROOT, 'index.json'), 'utf8'))
  : { effects: {} };

let failed = 0;
for (const entry of chosen) {
  try {
    const fx = await loadEffect(entry.effect);
    // Effects are authored with a stock character; games never want him.
    let fps = entry.fps ?? 20;
    const probe = renderFrames(fx, { fps, bg: 'none', actor: false });
    const wantedWidth = probe.w * probe.n;
    if (wantedWidth > MAX_STRIP_WIDTH) {
      // Drop frames rather than ship a texture the browser refuses to upload.
      fps = Math.max(4, Math.floor((MAX_STRIP_WIDTH / probe.w) / (probe.n / fps)));
    }
    const r = fps === (entry.fps ?? 20) ? probe : renderFrames(fx, { fps, bg: 'none', actor: false });

    const { w, h, n, frames } = r;
    const strip = new Uint8ClampedArray(w * n * h * 4);
    frames.forEach((frame, i) => {
      const src = frame.clear;
      for (let y = 0; y < h; y += 1) {
        const from = y * w * 4;
        const to = (y * w * n + i * w) * 4;
        strip.set(src.subarray(from, from + w * 4), to);
      }
    });

    const dir = join(OUT_ROOT, entry.slug);
    mkdirSync(dir, { recursive: true });
    writeFileSync(join(dir, 'strip.png'), encodePNG(w * n, h, strip));

    const [pivotX, pivotY] = fx.meta.origin;
    const manifest = {
      slug: entry.slug,
      id: fx.id,
      name: fx.meta.name,
      source: `https://github.com/patch-gg/pixelfx/blob/main/src/fx/${entry.effect}.js`,
      sheet: 'strip.png',
      layout: 'strip',
      frames: n,
      frameWidth: w,
      frameHeight: h,
      fps: r.fps,
      loop: entry.loop ?? Boolean(fx.meta.loop),
      durationMs: Math.round((n / r.fps) * 1000),
      pivot: [pivotX, pivotY],
      generatedBy: 'scripts/vfx/export.mjs',
    };
    writeFileSync(join(dir, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`);
    index.effects[entry.slug] = manifest;

    const kb = Math.round((strip.length / 1024) * 0.15); // rough: PNG ~ palette art
    console.log(
      `${entry.slug.padEnd(18)} ${String(n).padStart(4)} frames  ${w}x${h}  ${r.fps}fps  ` +
        `${(n / r.fps).toFixed(2)}s  strip ${w * n}x${h}  ~${kb}KB`,
    );
  } catch (err) {
    failed += 1;
    console.error(`${entry.slug.padEnd(18)} FAILED: ${err.message}`);
  }
}

writeFileSync(join(OUT_ROOT, 'index.json'), `${JSON.stringify(index, null, 2)}\n`);

// Typed metadata for the games, so frame counts and durations are never
// duplicated by hand in game code.
const sorted = Object.keys(index.effects).sort();
const lines = [
  '// GENERATED by scripts/vfx/export.mjs — do not edit by hand.',
  '// Regenerate with: npm run vfx',
  '',
  'export interface PixelFxMeta {',
  '  readonly slug: string;',
  '  readonly id: string;',
  '  readonly name: string;',
  '  readonly frames: number;',
  '  readonly frameWidth: number;',
  '  readonly frameHeight: number;',
  '  readonly fps: number;',
  '  readonly loop: boolean;',
  '  readonly durationMs: number;',
  '  readonly pivot: readonly [number, number];',
  '}',
  '',
  'export const PIXEL_FX = {',
  ...sorted.map((slug) => {
    const e = index.effects[slug];
    return (
      `  ${JSON.stringify(slug)}: { slug: ${JSON.stringify(e.slug)}, id: ${JSON.stringify(e.id)}, ` +
      `name: ${JSON.stringify(e.name)}, frames: ${e.frames}, frameWidth: ${e.frameWidth}, ` +
      `frameHeight: ${e.frameHeight}, fps: ${e.fps}, loop: ${e.loop}, ` +
      `durationMs: ${e.durationMs}, pivot: [${e.pivot[0]}, ${e.pivot[1]}] },`
    );
  }),
  '} as const satisfies Record<string, PixelFxMeta>;',
  '',
  'export type PixelFxSlug = keyof typeof PIXEL_FX;',
  '',
];
writeFileSync(join(GAME_ROOT, 'frontend', 'src', 'games', 'pixelFx.generated.ts'), lines.join('\n'));

if (failed) process.exit(1);
