#!/usr/bin/env python3
"""Recolor the flat chroma backdrop of generated strips to the run's magenta key.

The free Pollinations `flux` model renders "magenta #FF00FF" as a hot pink
(~(248,15,100)) instead of the exact key, so rows generated by the pollinations
provider would not key cleanly in the frame extractor (which keys tolerance
distances around #FF00FF). This step border-flood-fills the contiguous backdrop
to the exact key color, image per image.

Only pixels reachable from the image borders through backdrop-colored pixels are
repainted. Subject pixels are never touched (magenta is a color casino props
don't contain, which is why the pipeline keys on it).

NOTE on floor glow: flux occasionally paints a light-pink floor glow/stand band
across the bottom of a strip, fusing all frames into one component. Flood-filling
that band by color tolerance is unsafe (it eats bright subject pixels), so it is
NOT handled here — prevent it at the prompt level instead by explicitly banning
floor/ground/pedestal/shadow/glow/bloom in the row prompt (see
prepare-all.mjs CHROMA).

Usage: venv python scripts/sprite-gen/rekey-backdrop.py <run-dir> [--tol TOL]
       TOL = Euclidean RGB distance of a pixel from the border backdrop color that
       still counts as backdrop (default 60; flux's pink sits within ~15 of its
       family center, subjects are ~150+ away, so 60 is a safe middle).
"""

import argparse
import sys
from collections import deque
from pathlib import Path

from PIL import Image

TARGET = (255, 0, 255)  # #FF00FF


def _dist(a, b):
    return ((a[0] - b[0]) ** 2 + (a[1] - b[1]) ** 2 + (a[2] - b[2]) ** 2) ** 0.5


def _median_color(colors):
    if not colors:
        return None
    colors = sorted(colors)
    return colors[len(colors) // 2]


def recolor_strip(path: Path, tol: float) -> int:
    im = Image.open(path)
    if im.mode != "RGB":
        im = im.convert("RGB")
    w, h = im.size
    px = im.load()
    orig = list(im.getdata())

    border = [orig[y * w + x] for y in range(h) for x in range(w)
              if x == 0 or x == w - 1 or y == 0 or y == h - 1]
    if not border:
        return 0
    bg_family = _median_color(border)

    visited = bytearray(w * h)
    queue = deque()

    def enqueue(x, y):
        idx = y * w + x
        if not visited[idx] and _dist(orig[idx], bg_family) <= tol:
            visited[idx] = 1
            queue.append((x, y))

    for y in range(h):
        for x in range(w):
            if x == 0 or x == w - 1 or y == 0 or y == h - 1:
                idx = y * w + x
                visited[idx] = 1
                if _dist(orig[idx], bg_family) <= tol:
                    queue.append((x, y))

    count = 0
    while queue:
        x, y = queue.popleft()
        if px[x, y] != TARGET:
            px[x, y] = TARGET
            count += 1
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if 0 <= nx < w and 0 <= ny < h:
                enqueue(nx, ny)

    im.save(path, format="PNG")
    return count


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("run_dir", type=Path, help="prepared+sprite-gen run directory")
    parser.add_argument("--tol", type=float, default=60.0, help="background distance tolerance (default 60)")
    args = parser.parse_args()

    raw = args.run_dir / "raw"
    if not raw.is_dir():
        print(f"no raw/ directory in {args.run_dir}", file=sys.stderr)
        return 2

    total = 0
    for strip in sorted(raw.glob("*.png")):
        count = recolor_strip(strip, args.tol)
        im = Image.open(strip)
        w, h = im.size
        px = im.load()
        magenta = sum(1 for y in range(h) for x in range(w) if px[x, y] == TARGET)
        pct = magenta / (w * h) * 100
        print(f"{strip.name}: repainted {count} px | magenta now {pct:.1f}%")
        total += count
    print(f"done: {total} pixels recolored across {args.run_dir}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())